/**
 * The 17 library sections, re-cast as drills inside a unit.
 * See the plan's «كل قسم من الـ١٧ يصير نوع نشاط داخل الوحدة» table.
 */
export type ActivityKind =
  | 'explanation'        // الشرح: the teaching card that opens a group
  | 'word-intro'         // المفردات — تعرّف: the six-stage new-word card
  | 'word-recall'        // المفردات — استدعاء: recognition/production recall
  | 'hanzi-write'        // الحروف: trace the character in stroke order
  | 'tone-discriminate'  // البينين: pick the tone you heard / that fits
  | 'pinyin-match'       // البينين: match syllable ↔ character
  | 'pronounce'          // تدريب النطق: say it, get scored
  | 'image-match'        // القاموس البصري: picture ↔ word
  | 'grammar-brief'      // القواعد: the micro-explanation
  | 'grammar-apply'      // القواعد: apply it immediately
  | 'sentence-order'     // الجمل: reorder tokens into a sentence
  | 'fill-blank'         // الجمل: fill the gap
  | 'translate'          // الجمل: translate both directions
  | 'roleplay'           // المحادثات: choose the speaker's reply
  | 'story-excerpt'      // القصص: passage + comprehension question
  | 'daily-qa'           // أسئلة يومية: a life question with a model answer
  | 'game-break'         // الألعاب: the every-six-activities breather
  | 'exam-style'         // محاكي الامتحان: HSK-format items closing the lesson

/** Where an activity sits on the recognition → production ramp. */
export type ActivityMode = 'present' | 'recognise' | 'produce' | 'break'

/**
 * [4.2] A string the learner reads, in both languages.
 *
 * The activity engine used to build its user-facing copy as bare Arabic
 * template literals — «النبرة ٣», «بماذا يردّ ليلى؟», «اكتب من الأعلى إلى
 * الأسفل» — eleven of them, reaching seven of the seventeen activity kinds.
 * There was no `locale` anywhere in the engine to consult, so an English
 * learner met Arabic instructions on every tone drill, every role-play and
 * every writing board.
 *
 * Both languages travel together in the payload rather than the engine taking a
 * locale, which keeps `buildActivityStream` pure and lets ONE built stream serve
 * both routes.
 */
export interface Bilingual {
  ar: string
  en: string
}

/** Pick the reader's side of a bilingual string. */
export function say(text: Bilingual, locale: 'ar' | 'en'): string {
  return locale === 'en' ? text.en : text.ar
}

// ── [2.1] The explanation ───────────────────────────────────────────────────

/** One worked example. Both languages, always — see [4.6]. */
export interface ExplanationExample {
  zh: string
  pinyin: string
  ar: string
  en: string
}

/**
 * A mistake learners actually make, and what to do instead.
 *
 * Not decoration. Naming the wrong form beside the right one is what stops a
 * learner inventing «我是很好» from an English habit; a rule stated only in the
 * positive leaves every wrong path equally plausible.
 */
export interface CommonMistake {
  /** The wrong form, as a learner would write it. */
  wrongZh: string
  /** The corrected form. */
  rightZh: string
  whyAr: string
  whyEn: string
}

/** Why the engine emitted this activity — drives copy and progress weighting. */
export type ActivitySource =
  /** First encounter with a word of this unit. */
  | 'new'
  /** Practice of a word this unit owns. */
  | 'practice'
  /** SRS review pulled in from an earlier unit. */
  | 'review'
  /** Extra repetition because the learner has missed this word. */
  | 'remediation'
  /** Lesson-closing assessment. */
  | 'assessment'

export interface ActivityBase {
  /** Deterministic id: `${unitKey}#${index}-${kind}`. Stable for a given seed. */
  id: string
  kind: ActivityKind
  mode: ActivityMode
  source: ActivitySource
  unit: UnitRef
  /** Words this activity exercises — what SRS should be graded against. */
  wordIds: number[]
  /** 0-based position in the stream. */
  index: number
}

// ── Shared payload fragments ────────────────────────────────────────────────

export interface SentenceRef {
  zh: string
  pinyin: string
  ar: string
}

export interface RadicalPart {
  char: string
  /** Arabic gloss of the component, empty when the source data has none. */
  meaning: string
}

/** A choice in any multiple-choice drill. */
export interface Choice {
  /** Primary label — Chinese, pinyin or Arabic depending on the drill. */
  label: string
  /**
   * The label in English, where it differs.
   *
   * Most choices are Chinese or pinyin and read the same on both routes, so
   * this is absent for them. It exists for the few whose label is prose — the
   * exam's «✓ صحيح / ✗ خطأ» being the case that forced it.
   *
   * NOT YET COVERED, and it is a content gap rather than a wiring one: a
   * `translate` drill in the zh→ar direction labels its options with the
   * sentence's Arabic, and the corpus has no English for 1,890 of those
   * sentences. Those options stay Arabic on the English route until the
   * translations are authored; `audit-content.js` counts them.
   */
  labelEn?: string
  /** Optional secondary line under the label (design shows both). */
  sub?: string
  /** Word id behind this choice, when the choice is a vocabulary word. */
  wordId?: number
}

export interface MultipleChoice {
  choices: Choice[]
  /** Index into `choices`. */
  correct: number
  /**
   * Explanation shown in the verdict bar — always present.
   *
   * `en` may be empty where the SOURCE DATA has no English (the HSK1 exam
   * bank's explanations are Arabic-only, and 1,079 mnemonics have no English
   * field at all). The view falls back to the Arabic in that case rather than
   * showing an empty verdict: a learner who has just answered deserves to be
   * told why, and a wrong-language reason beats no reason. The gap is content,
   * counted by `audit-content.js`, and closes as the English is authored.
   */
  explanation: Bilingual
}

