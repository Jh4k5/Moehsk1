/**
 * One topical unit cut out of a lesson. Generated by `scripts/build-units.js`
 * into `src/data/units/units.generated.ts` — do not hand-edit that file.
 */
export interface Unit {
  ref: UnitRef
  /** `${level}:${lesson}:${unit}` — duplicated onto the record for cheap lookup. */
  key: UnitKey
  /** Arabic title, derived from the unit's own words. */
  title: string
  /** The same title in English. Both languages, always — see [4.6]. */
  titleEn: string
  /** One-line Arabic goal, derived from the unit's own words. */
  goal: string
  /** Vocabulary ids owned by this unit. Every lesson word lands in exactly one. */
  wordIds: number[]
  /** Grammar rule ids the unit may draw a `grammar-brief` from. */
  grammarIds: number[]
  /** Indices into `lesson.keySentences` this unit's words actually appear in. */
  keySentenceIndices: number[]
  /** Ids of `conversations` (level-scoped) whose turns use this unit's words. */
  conversationIds: number[]
  /** True for the last unit of its lesson — it carries the lesson's exam items. */
  carriesExam: boolean
  /** Hanzi characters introduced by this unit's words, in first-appearance order. */
  hanzi: string[]
}

