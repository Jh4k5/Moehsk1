/**
 * A unit's title in the locale being served.
 *
 * Every screen used to render `unit.title` directly, which is the Arabic one,
 * so the English path listed an entire curriculum under Arabic headings. A
 * helper rather than a field access because there are six call sites and a
 * seventh will be added by someone who has not read this file.
 *
 * Falls back to the Arabic when `titleEn` is absent — unlike a sentence gloss,
 * a missing title cannot be dropped: a unit with no name is unnavigable, and a
 * name in the wrong language still tells the reader which unit it is.
 */
export function unitTitle(
  unit: { title: string; titleEn?: string },
  locale: 'ar' | 'en',
): string {
  if (locale !== 'en') return unit.title
  return unit.titleEn?.trim() || unit.title
}

// ── Learner state the engine reads ──────────────────────────────────────────

/**
 * The slice of learner state `buildActivityStream` needs. Deliberately a plain
 * structure, not the Zustand store, so the engine stays pure and testable.
 */
export interface LearnerState {
  /** SM-2 cards keyed by word id — `srsCards` from the store, as-is. */
  srsCards: Record<number, LearnerSrsCard>
  /** Units already completed, as `UnitKey`s. Drives review depth and unlock. */
  completedUnits: UnitKey[]
  /** Words the learner has answered wrong recently, most recent first. */
  missedWordIds: number[]
  /** Seed for the deterministic shuffles. Same seed ⇒ identical stream. */
  seed: number
}

/** Structural subset of `SRSCard` from `src/lib/srs.ts`. */
export interface LearnerSrsCard {
  wordId: number
  easeFactor: number
  interval: number
  repetitions: number
  nextReview: string | null
  lastReview: string | null
  reviewCount: number
  correctCount: number
}

export function emptyLearnerState(seed = 1): LearnerState {
  return { srsCards: {}, completedUnits: [], missedWordIds: [], seed }
}

