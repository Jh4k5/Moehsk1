// ─────────────────────────────────────────────────────────────────────────────
// Curriculum types — level → lesson → unit → activity stream.
//
// A *unit* is the completable study session (5–8 words, 5–8 minutes). A unit's
// activity stream is built at runtime by `buildActivityStream`; nothing here is
// persisted beyond the generated unit table in `src/data/units/`.
//
// Every activity carries exactly the payload its screen needs, modelled from
// the approved design files in `design/`:
//   WordCard.dc.html → word-intro      Writing.dc.html → hanzi-write
//   Activity.dc.html → roleplay        Path.dc.html    → unit shape + ordering
// ─────────────────────────────────────────────────────────────────────────────

export type HskLevelNo = 1 | 2 | 3

/**
 * Composite address of a unit. Lesson ids collide across levels
 * (HSK1 1..15, HSK2 1..15, HSK3 1..18), so `level` is never optional.
 */
export interface UnitRef {
  level: HskLevelNo
  /** Lesson id as it appears in that level's `lessons[].id`. */
  lesson: number
  /** 1-based ordinal of the unit inside its lesson. */
  unit: number
}

/** Stable string key for a UnitRef — safe as a React key, map key or DB key. */
export type UnitKey = `${HskLevelNo}:${number}:${number}`

export function unitKey(ref: UnitRef): UnitKey {
  return `${ref.level}:${ref.lesson}:${ref.unit}`
}

export function parseUnitKey(key: string): UnitRef | null {
  const m = /^([123]):(\d+):(\d+)$/.exec(key)
  if (!m) return null
  return { level: Number(m[1]) as HskLevelNo, lesson: Number(m[2]), unit: Number(m[3]) }
}

export function sameUnit(a: UnitRef, b: UnitRef): boolean {
  return a.level === b.level && a.lesson === b.lesson && a.unit === b.unit
}

