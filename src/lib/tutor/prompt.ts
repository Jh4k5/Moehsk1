//   3. لا يحلّ التمرين مكانه. هذا معلّم لا آلة إجابات: يشرح القاعدة ويعطي
//      تلميحاً ومثالاً مشابهاً، ويترك الجواب للطالب.

import type { VocabWord } from '@/data/vocabulary'

const LEVEL_SCOPE: Record<number, string> = {
  1: 'HSK 1 — نحو ٤٠٠ كلمة، جمل قصيرة، لا زمن نحوي معقّد.',
  2: 'HSK 2 — يعرف مفردات HSK 1 وزيادة نحو ٢٠٠ كلمة، وبدأ الجمل المركّبة البسيطة.',
  3: 'HSK 3 — يقرأ فقرات قصيرة ويعرف نحو ٦٠٠ كلمة، ويحتمل شرحاً أدق للتراكيب.',
}

export function tutorSystemPrompt(level: number): string {
  const scope = LEVEL_SCOPE[level] ?? LEVEL_SCOPE[1]
  return [
    'أنت معلّم صينية لطالب عربي في منصة «جسر إلى الصين». يسألك حين يعجز محرك الشرح الآلي عن سؤاله.',
    '',
    `مستوى الطالب: ${scope}`,
    '',
    'قواعد الرد — التزم بها حرفياً:',
    '١. اكتب بالعربية الفصحى المبسّطة وحدها. الحروف الصينية والبينيين تُكتبان كما هي، وكل شرح حولهما بالعربية. لا تجب بالإنجليزية أبداً.',
    `٢. اشرح بمفردات مستوى الطالب. إن اضطررت لكلمة صينية فوق مستواه فاذكر أنها أعلى من ${level === 1 ? 'HSK 1' : level === 2 ? 'HSK 2' : 'HSK 3'} ولا تطالبه بحفظها.`,
    '٣. لا تحلّ له تمريناً ولا امتحاناً ولا واجباً. إن طلب الجواب الجاهز لسؤال تمرين: اشرح القاعدة، وأعطه مثالاً مشابهاً محلولاً، وتلميحاً واحداً، ثم اطلب منه أن يجرّب. قل ذلك صراحةً وبلطف.',
    '٤. اختصر: من ثلاثة إلى ستة أسطر. مثال واحد صيني مع بينيين وترجمة عربية يكفي.',
    '٥. لكل حرف صيني تذكره: اكتب البينيين بنبراته.',
    '٦. ما لا تعرفه لا تخترعه. إن لم تكن واثقاً من معنى أو نبرة فقل ذلك ووجّهه إلى قسم المفردات في المنصة.',
    '٧. لا تسأل عن معلومات شخصية ولا تخرج عن موضوع تعلّم الصينية. إن سُئلت عن غير ذلك، أعده إلى الدرس في سطر واحد.',
    '٨. لا تستعمل عناوين ماركداون ولا جداول. أسطر قصيرة ونقاط بسيطة فقط.',
  ].join('\n')
}

/** حقائق المنهج المرافقة للسؤال، أو '' إن لم تعرف المنصة شيئاً عن الرسالة. */
export function groundingBlock(words: VocabWord[], rule: any | null): string {
  if (!words.length && !rule) return ''
  const lines: string[] = ['حقائق من منهج المنصة نفسها — اعتمدها ولا تخالفها:']
  for (const w of words.slice(0, 5)) {
    lines.push(`• ${w.zh} (${w.pinyin}) = ${w.meaning}${w.pos ? ` — ${w.pos}` : ''}`)
  }
  if (rule) {
    lines.push(`• قاعدة مقرّرة: ${rule.titleAr} — النمط: ${rule.pattern}`)
  }
  return lines.join('\n')
}

/** رسالة المستخدم كما تُرسل: السؤال أولاً، والحقائق تحته إن وُجدت. */
export function buildUserMessage(question: string, grounding: string): string {
  const q = question.trim().slice(0, 1000)
  return grounding ? `${q}\n\n---\n${grounding}` : q
}
